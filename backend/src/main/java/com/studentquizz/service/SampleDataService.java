    private User ensureAdmin() {
        String adminEmail = "ngotrungchien232@gmail.com";
        return userRepository.findByEmail(adminEmail).orElseGet(() ->
                userRepository.save(User.builder()
                        .name("Ngô Trung Chiến")
                        .email(adminEmail)
                        .password(passwordEncoder.encode("14102005"))
                        .role("ADMIN")
                        .locked(false)
                        .build()));
    }

    private User ensureDemoUser() {
        return userRepository.findByEmail(DEMO_EMAIL).map(existing -> {
            boolean changed = false;
            if (!passwordEncoder.matches(DEMO_PASSWORD, existing.getPassword())) {
                existing.setPassword(passwordEncoder.encode(DEMO_PASSWORD));
                changed = true;
            }
            if (Boolean.TRUE.equals(existing.getLocked())) {
                existing.setLocked(false);
                existing.setLockReason(null);
                changed = true;
            }
            return changed ? userRepository.save(existing) : existing;
        }).orElseGet(() -> userRepository.save(User.builder()
                .name("Người dùng Demo")
                .email(DEMO_EMAIL)
                .password(passwordEncoder.encode(DEMO_PASSWORD))
                .role("USER")
                .locked(false)
                .build()));
    }

